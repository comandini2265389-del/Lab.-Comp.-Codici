import numpy as np
import matplotlib.pyplot as plt

x,y,z=np.loadtxt("pendolo0.2.dat",unpack=True,usecols=(0,1,2))
plt.grid()
plt.title("Traiettoria con $\Theta=0,2$")
plt.xlabel("$t$")
plt.ylabel("$\Theta(t)$")
plt.plot(x,y,'gd',label="Traiettoria")
plt.legend()
plt.savefig("PendoloTraierttoria0.2.pdf")
plt.show()
plt.grid()

plt.title("Velocità con $\Theta=0.2$")
plt.plot(x,z, 'mo', label="Velocità")
plt.xlabel("$t$")
plt.ylabel("$\omega(t)$")
plt.legend()
plt.savefig("PendoloVelocità0.2.pdf")
plt.show()

plt.title("Spazio delle fasi con $\Theta=0.2$")
plt.grid()
plt.plot(y,z, )
plt.xlabel("$\Theta(t)$")
plt.ylabel("$\omega(t)$")
plt.legend()
plt.savefig("PendoloFasi0.2.pdf")
plt.show()

